// 主题(皮肤)系统定义。
//
// 每套主题 = antd token(交给 ConfigProvider 的算法与令牌)+ CSS 变量
// (供自定义样式的背景/边框使用,变量以 --hitk- 前缀注入 <html>)。
// 新增主题:在此追加一项即可,运行时热切换,选择持久化(偏好项 key: theme)。

export interface HitKTheme {
  /** 皮肤 id,同时作为持久化设置值 */
  id: string
  /** 显示名 */
  name: string
  /** 说明 */
  desc: string
  /** 是否暗色(决定 antd 算法) */
  dark: boolean
  /** antd 主题令牌(colorPrimary 等) */
  token: Record<string, string | number>
  /** CSS 变量映射(--hitk-{key}) */
  vars: Record<string, string>
}

